#!/usr/bin/env bash
# Round 7 cases for .claude/hooks/guard-bash.sh: contents API branch field, git config editors, workflow
# protection, named-fd redirections, writes to parent directories, tag lease pushes, missing pre-push hook.
# Cases are data passed to the hook; nothing here executes them.
# shellcheck disable=SC2016  # single quotes are intentional: cases are literal command text
set -euo pipefail
root=$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)
guard=${GUARD:-$root/.claude/hooks/guard-bash.sh}
fail=0
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
git init -q -b main "$tmp/onmain"; git init -q -b feat/x "$tmp/onfeat"; git init -q -b feat/x "$tmp/nohook"; git init -q -b feat/x "$tmp/nonexec"
for r in onmain onfeat; do mkdir -p "$tmp/$r/.githooks"; : >"$tmp/$r/.githooks/pre-push"; chmod +x "$tmp/$r/.githooks/pre-push"; done
mkdir -p "$tmp/nonexec/.githooks" "$tmp/onfeat/.claude/hooks" "$tmp/onfeat/.github/workflows" "$tmp/home/.config/systemd/user" "$tmp/onfeat/sub"
: >"$tmp/nonexec/.githooks/pre-push"

run() { jq -n --arg c "$1" --arg d "${2:-}" '{tool_input: {command: $c}} + (if $d == "" then {} else {cwd: $d} end)' | HOME=$tmp/home "$guard" >/dev/null 2>&1; }
allow() { if run "$1" "${2:-}"; then echo "ok   allow: $1"; else echo "FAIL should allow: $(printf '%q' "$1")"; fail=1; fi; }
deny()  { if run "$1" "${2:-}"; then echo "FAIL should deny: $(printf '%q' "$1")"; fail=1; else echo "ok   deny:  $(printf '%q' "$1")"; fi; }
F=$tmp/onfeat

# --- 1. contents API: the key is exactly `branch`, the value names a feature branch --------------
deny  "gh api -X PUT repos/o/r/contents/a -f Branch=feat/x -f content=x" "$F"
deny  "gh api -X PUT repos/o/r/contents/a -f BRANCH=feat/x -f content=x" "$F"
deny  "gh api -X PUT repos/o/r/contents/a -f branch= -f content=x" "$F"
deny  "gh api -X PUT repos/o/r/contents/a -f branch=refs/heads/ -f content=x" "$F"
deny  "gh api -X PUT repos/o/r/contents/a -f branch=heads/ -f content=x" "$F"
deny  "gh api -X PUT repos/o/r/contents/a -f branch=refs/ -f content=x" "$F"
deny  "gh api -X PUT repos/o/r/contents/a -f branch=@b.txt -f content=x" "$F"
deny  "gh api -X PUT repos/o/r/contents/a -F branch=@- -f content=x" "$F"
deny  "gh api -X PUT repos/o/r/contents/a -f branch=heads/MAIN -f content=x" "$F"
deny  "gh api -X PUT repos/o/r/contents/a -f branch=refs/heads/Master -f content=x" "$F"
deny  "gh api -X PUT repos/o/r/contents/a -f branch=feat/x -f branch=@b.txt" "$F"
allow "gh api -X PUT repos/o/r/contents/actions/a.txt -f message=m -f content=eA== -f branch=feat/x" "$F"

# --- 2. git config editors ----------------------------------------------------------------------
deny  "git config -e" "$F"
deny  "git config --edit" "$F"
deny  "git config --global -e" "$F"
deny  "git config --global --edit" "$F"
deny  "git config --local --edit" "$F"
deny  "git -c core.editor=vim commit" "$F"
deny  "git -ccore.editor=vim commit" "$F"
deny  "git -c sequence.editor=x rebase -i HEAD~2" "$F"
deny  "git config core.editor vim" "$F"
deny  "git config --global sequence.editor x" "$F"
deny  "git config --unset core.editor" "$F"
deny  "git --config-env=core.editor=ED commit" "$F"
deny  "GIT_EDITOR=true git rebase -i HEAD~2" "$F"
deny  "GIT_SEQUENCE_EDITOR=x git rebase -i HEAD~2" "$F"
deny  "EDITOR=vi git commit" "$F"
deny  "VISUAL=x git commit" "$F"
deny  "env GIT_EDITOR=x git commit" "$F"
deny  "GIT_EDITOR='x y' git commit" "$F"
allow "git config --get core.editor" "$F"
allow "git config -l" "$F"
allow "git config --list" "$F"
allow 'git commit -m "set EDITOR=vi and GIT_EDITOR=x"' "$F"
allow "EDITOR=vi cargo test" "$F"

# --- 3. workflows are privileged ----------------------------------------------------------------
deny  "echo x > .github/workflows/ci.yml" "$F"
deny  "echo x >> .github/workflows/ci.yml" "$F"
deny  "printf x | tee .github/workflows/ci.yml" "$F"
deny  "cp /tmp/x .github/workflows/ci.yml" "$F"
deny  "mv /tmp/x .github/workflows/ci.yml" "$F"
deny  "sed -i s/a/b/ .github/workflows/ci.yml" "$F"
deny  "rm .github/workflows/ci.yml" "$F"
deny  "rm -rf .github/workflows" "$F"
deny  "git checkout HEAD~1 -- .github/workflows/ci.yml" "$F"
deny  "echo x > ../.github/workflows/ci.yml" "$F/sub"
deny  "WARDENLENS_ALLOW_WORKFLOWS=1 git push origin feat/x" "$F"
deny  "export WARDENLENS_ALLOW_WORKFLOWS=1" "$F"
deny  "env WARDENLENS_ALLOW_WORKFLOWS=1 git push origin feat/x" "$F"
deny  "bash -c 'WARDENLENS_ALLOW_WORKFLOWS=1 git push origin feat/x'" "$F"
deny  "declare -x WARDENLENS_ALLOW_WORKFLOWS" "$F"
deny  "WARDENLENS_ALLOW_WORKFLOWS+=1 git push origin feat/x" "$F"
allow 'git commit -m "document WARDENLENS_ALLOW_WORKFLOWS for humans"' "$F"
allow "git add .github/workflows/ci.yml" "$F"
allow "cat .github/workflows/ci.yml" "$F"
deny  "gh workflow run ci.yml --ref feat/x" "$F"
deny  "gh workflow run ci.yml -r feat/x" "$F"
deny  "gh workflow run ci.yml --ref=feat/x" "$F"
deny  "gh workflow run ci.yml -rfeat/x" "$F"
deny  "gh workflow run ci.yml --ref" "$F"
deny  "gh workflow run ci.yml -f a=b --ref refs/heads/other" "$F"
deny  "gh -R o/r workflow run ci.yml --ref feat/x" "$F"
allow "gh workflow run ci.yml" "$F"
allow "gh workflow run ci.yml --ref main" "$F"
allow "gh workflow run ci.yml -r main" "$F"
allow "gh workflow run ci.yml --ref=refs/heads/main" "$F"
allow "gh workflow list" "$F"
deny  "gh api -X POST repos/o/r/actions/workflows/ci.yml/dispatches -f ref=feat/x" "$F"
deny  "gh api repos/o/r/actions/workflows/1/dispatches -f ref=x" "$F"
deny  "gh api -X POST repos/o/r/actions/runs/1/rerun" "$F"
deny  "gh api -X DELETE repos/o/r/actions/secrets/X" "$F"
deny  "gh api -X PUT repos/o/r/environments/prod" "$F"
deny  "gh api -X PUT repos/o/r/environments" "$F"
deny  "gh api -X POST repos/o/r/./actions/runs/1/cancel" "$F"
allow "gh api repos/o/r/actions/runs" "$F"
allow "gh api repos/o/r/environments" "$F"

# --- 4. named-fd redirections -------------------------------------------------------------------
deny  "git {fd}>/dev/null push --force origin feat/x" "$F"
deny  "git {fd}>>/dev/null push --force origin feat/x" "$F"
deny  "git {fd}</dev/null push --force origin feat/x" "$F"
deny  "git {fd}<>/dev/null push --force origin feat/x" "$F"
deny  "git {fd}>&2 push --force origin feat/x" "$F"
deny  "git {fd}<&0 push --force origin feat/x" "$F"
deny  "git {my_fd9}>&- push origin main" "$F"
deny  "{_x}>/dev/null git commit -n -m x" "$F"
deny  "echo x {fd}>.githooks/pre-push" "$F"
deny  "echo x {fd}>>.github/workflows/ci.yml" "$F"
allow "echo hi {fd}>/tmp/out.txt" "$F"
allow "echo {a,b}" "$F"

# --- 5. writes to parent directories ------------------------------------------------------------
deny  "rm -rf .github" "$F"
deny  "rm -rf .claude/" "$F"
deny  "rm -rf ./.claude/." "$F"
deny  "rm -rf ." "$F"
deny  "rm -rf .." "$F/sub"
deny  "rm -rf $F" "$tmp"
deny  "rm -rf $tmp" "$F"
deny  "mv . /tmp/elsewhere" "$F"
deny  "mv .github /tmp/gh" "$F"
deny  "chmod -R u+w ." "$F"
deny  "chmod -R 000 .github" "$F"
deny  "chown -R nobody ." "$F"
deny  "rsync -a --delete /tmp/empty/ ./" "$F"
deny  "rsync -a /tmp/x/ .github/" "$F"
deny  "cp -r /tmp/x ." "$F"
deny  "cp -r /tmp/x .github/" "$F"
deny  "install -d .claude" "$F"
deny  "ln -sfn /tmp/x .claude" "$F"
deny  "find .claude -delete" "$F"
deny  "find . -delete" "$F"
deny  "find . -exec rm -rf {} +" "$F"
deny  "find . -name '*' -delete" "$F"
deny  "find . -name '*.orig' -o -delete" "$F"
deny  "find . -name .git -delete" "$F"
deny  "find ~ -name '*.orig' -delete" "$F"
deny  "rm -rf ~" "$F"
deny  "rm -rf ~/.config" "$F"
deny  "rm -rf ~/.config/systemd" "$F"
deny  "rm -rf \$HOME/.config" "$F"
deny  "mv ~/.config /tmp/c" "$F"
deny  "rm -rf /" "$F"
deny  "rm -rf /tmp/../" "$F"
deny  "echo a; cd sub; rm -rf .claude" "$F"
deny  "echo a; cd sub; rm -rf .github" "$F"
deny  "echo a; cd sub; echo x > rustfmt.sh" "$F"
deny  "echo a; cd sub; cp /tmp/x rustfmt.sh" "$F"
allow "rm -rf target" "$F"
allow "rm -rf $F/target" "$tmp/onmain"
allow "rm -f /tmp/x.txt" "$F"
allow "mv a.txt b.txt" "$F"
allow "mv sub/a.txt sub/b.txt" "$F"
allow "chmod +x scripts/gate" "$F"
allow "cp Cargo.toml /tmp/Cargo.toml" "$F"
allow "cp -r /tmp/x sub/" "$F"
allow "cp -r /tmp/x sub" "$F"
allow "install -m755 /tmp/x sub/x" "$F"
allow "find . -name '*.orig' -delete" "$F"
allow "find . -iname '*.bak' -exec rm {} +" "$F"
allow "find . -name '*.rs' -exec grep -l foo {} +" "$F"
allow "find .git -type f -exec grep -l foo {} +" "$F"
allow "find . -type f -exec cat {} +" "$F"
allow "find . -name '*.rs'" "$F"
allow "rsync -a --exclude=.git /tmp/a/ /tmp/b/" "$F"
allow "rsync -a --exclude .git --exclude .claude /tmp/a/ /tmp/b/" "$F"
allow "cargo install --path ." "$F"
allow "cargo install cargo-deny --locked" "$F"
allow "git rm --cached foo" "$F"

# --- 6. tag leases, missing pre-push hook -------------------------------------------------------
deny  "git push --force-with-lease origin v1:refs/tags/v1" "$F"
deny  "git push --force-with-lease origin HEAD:refs/tags/v1" "$F"
deny  "git push --force-if-includes origin v1:refs/tags/v1" "$F"
deny  "git push --force-with-lease=refs/tags/v1:abc origin v1" "$F"
deny  "git push --force-with-lease --tags origin" "$F"
deny  "git push --force-with-lease origin tag v1" "$F"
deny  "git push origin +v1:refs/tags/v1" "$F"
deny  "git push origin +HEAD:refs/tags/v1" "$F"
allow "git push --force-with-lease origin feat/x" "$F"
deny  "git push -u origin feat/x" "$tmp/nohook"
deny  "git push" "$tmp/nohook"
deny  "git -C $tmp/nohook push origin feat/x" "$F"
deny  "cd $tmp/nohook && git push origin feat/x" "$F"
deny  "git push -u origin feat/x" "$tmp/nonexec"
deny  "git -C $tmp/nonexec push" "$F"
allow "git push -u origin feat/x" "$F"
allow "git -C $F push origin feat/x" "$tmp/nohook"
allow "git push -u origin feat/x"
allow "echo a; cd /nonexistent; git push origin feat/x" "$tmp/nohook"

exit "$fail"
